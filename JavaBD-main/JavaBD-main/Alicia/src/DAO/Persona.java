package DAO;

public class Persona 
{
	private String nombre;
	private int dni;
	public Persona(String nombre, int dni)
	{
	
	}

	public String getNombre() {
		return nombre;
	}

	public void setNombre(String nombre) {
		this.nombre = nombre;
	}
	public int getDni()
	{
		return dni;
	}

}
